"""Analyze DDCD alpha sweep results and plot alpha vs success rate.

Reads the CSV generated by sweep_alpha.sh and produces a matplotlib plot
highlighting the optimal alpha value.

Usage:
    python examples/SimplerEnv/analyze_results.py --csv results/alpha_sweep.csv
    python examples/SimplerEnv/analyze_results.py --csv results/alpha_sweep.csv --output results/alpha_sweep.png
"""

import argparse
import logging
import sys

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


logging.basicConfig(level=logging.INFO, format="%(name)s - %(levelname)s - %(message)s")
logger = logging.getLogger(__name__)


def main():
    parser = argparse.ArgumentParser(description="Analyze DDCD alpha sweep results")
    parser.add_argument("--csv", type=str, required=True, help="Path to alpha_sweep.csv")
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Output plot path (default: <csv_dir>/alpha_sweep.png)",
    )
    args = parser.parse_args()

    df = pd.read_csv(args.csv)
    logger.info("Loaded %d rows from %s", len(df), args.csv)
    logger.info("\n%s", df.to_string(index=False))

    # Parse success_rate column (handle both percentage and decimal formats)
    rates = pd.to_numeric(df["success_rate"], errors="coerce")
    alphas = pd.to_numeric(df["alpha"], errors="coerce")

    valid = rates.notna() & alphas.notna()
    if valid.sum() == 0:
        logger.error("No valid numeric data found. Check CSV format.")
        return 1

    alphas = alphas[valid].values
    rates = rates[valid].values

    # If rates look like percentages (>1), convert to [0, 1]
    if np.any(rates > 1.0):
        rates = rates / 100.0

    # Find best alpha
    best_idx = np.argmax(rates)
    best_alpha = alphas[best_idx]
    best_rate = rates[best_idx]

    # Baseline (alpha=0.0)
    baseline_mask = alphas == 0.0
    baseline_rate = rates[baseline_mask][0] if baseline_mask.any() else None

    logger.info("Best alpha: %.2f (success rate: %.2f%%)", best_alpha, best_rate * 100)
    if baseline_rate is not None:
        improvement = (best_rate - baseline_rate) * 100
        logger.info(
            "Improvement over vanilla (alpha=0): +%.2f%% (%.2f%% -> %.2f%%)",
            improvement,
            baseline_rate * 100,
            best_rate * 100,
        )

    # Plot
    fig, ax = plt.subplots(figsize=(8, 5))

    ax.plot(alphas, rates * 100, "o-", color="#2563eb", linewidth=2, markersize=8, label="DDCD")

    # Highlight best point
    ax.plot(
        best_alpha,
        best_rate * 100,
        "*",
        color="#dc2626",
        markersize=18,
        zorder=5,
        label=f"Best: α={best_alpha:.1f} ({best_rate * 100:.1f}%)",
    )

    # Baseline line
    if baseline_rate is not None:
        ax.axhline(
            y=baseline_rate * 100,
            color="#9ca3af",
            linestyle="--",
            linewidth=1,
            label=f"Vanilla (α=0): {baseline_rate * 100:.1f}%",
        )

    ax.set_xlabel("Alpha (α)", fontsize=13)
    ax.set_ylabel("Success Rate (%)", fontsize=13)

    env_name = df["env_name"].iloc[0] if "env_name" in df.columns else "unknown"
    ax.set_title(f"DDCD Alpha Sweep — {env_name}", fontsize=14)
    ax.legend(fontsize=11)
    ax.grid(True, alpha=0.3)
    ax.set_xlim(alphas.min() - 0.1, alphas.max() + 0.1)

    # Y-axis range: show some margin
    ymin = max(0, rates.min() * 100 - 5)
    ymax = min(100, rates.max() * 100 + 5)
    ax.set_ylim(ymin, ymax)

    plt.tight_layout()

    if args.output is None:
        from pathlib import Path

        output_path = str(Path(args.csv).parent / "alpha_sweep.png")
    else:
        output_path = args.output

    fig.savefig(output_path, dpi=150)
    logger.info("Plot saved to: %s", output_path)
    plt.close(fig)

    return 0


if __name__ == "__main__":
    sys.exit(main())
